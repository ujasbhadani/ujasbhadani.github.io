// Generates docs/review-checklist.md from every `confirm: true` item across
// src/content — the founder's pre-merge (D5) review list described in
// docs/content-spec.md section 13. Run via `npm run review-checklist`.
//
// Sanity check after running: `grep -r "confirm: true" src/content | wc -l`
// should match the number of items listed below (docs/content-spec.md's
// own [confirm] marker count).
import { readFile, readdir, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";

const rootDir = path.resolve(import.meta.dirname, "..");
const contentDir = path.join(rootDir, "src/content");
const outputPath = path.join(rootDir, "docs/review-checklist.md");

const SECTION_LABELS = {
  experience: "3. Experience",
  education: "3.7 Education",
  lifecycle: "4. SOX 404(b) lifecycle",
  projects: "6. Projects",
  research: "7. Research",
  writing: "5. AI in GRC",
  skills: "8. Skills and certifications",
  certifications: "8. Skills and certifications",
  training: "8. Skills and certifications",
  awards: "9. Awards",
  recommendations: "10. Recommendations",
  caseStudies: "6. Projects (case studies)",
};

/** A human label for the entry an item was found in, used as context. */
function entryLabel(collection, data) {
  if (collection === "experience") return `${data.title} · ${data.org}`;
  if (collection === "lifecycle") return data.name;
  if (collection === "projects") return data.title;
  if (collection === "caseStudies") return data.title;
  return data.title || data.name || "";
}

// The rendered copy lives under different field names depending on which
// collection the `confirm: true` marker sits on (bullet-shaped objects use
// `text`; the lifecycle collection uses `sentence`; the projects collection
// uses `outcome`) -- checked in this order for whichever entry actually has
// `confirm: true` next to it.
const TEXT_FIELD_CANDIDATES = ["text", "sentence", "outcome"];

/** Recursively find every object with `confirm: true` under `node`. */
function findConfirmItems(node, acc) {
  if (Array.isArray(node)) {
    for (const item of node) findConfirmItems(item, acc);
    return;
  }
  if (node && typeof node === "object") {
    if (node.confirm === true) {
      const textField = TEXT_FIELD_CANDIDATES.find((field) => typeof node[field] === "string");
      if (textField) {
        acc.push({ text: node[textField], confirmNote: node.confirmNote });
      }
    }
    for (const value of Object.values(node)) findConfirmItems(value, acc);
  }
}

async function collectFromCollection(collection) {
  const dir = path.join(contentDir, collection);
  let files;
  try {
    files = (await readdir(dir)).filter((f) => f.endsWith(".json"));
  } catch {
    return [];
  }
  const results = [];
  for (const file of files.sort()) {
    const raw = await readFile(path.join(dir, file), "utf8");
    const data = JSON.parse(raw);
    const found = [];
    findConfirmItems(data, found);
    for (const item of found) {
      results.push({
        collection,
        section: SECTION_LABELS[collection] || collection,
        entry: entryLabel(collection, data),
        file,
        ...item,
      });
    }
  }
  return results;
}

async function main() {
  const collections = await readdir(contentDir);
  let items = [];
  for (const collection of collections.sort()) {
    items = items.concat(await collectFromCollection(collection));
  }

  const lines = [];
  lines.push("# Pre-merge content review checklist (D5)");
  lines.push("");
  lines.push(
    "Generated by `npm run review-checklist` (`scripts/review-checklist.mjs`) from every " +
      "`confirm: true` item under `src/content`, per docs/content-spec.md section 13. " +
      "Mark each item **true as written**, **true with edit**, or **not mine** before merge."
  );
  lines.push("");
  lines.push(`Total items: ${items.length}`);
  lines.push("");

  let n = 1;
  for (const item of items) {
    lines.push(`## ${n}. ${item.section} — ${item.entry}`);
    lines.push("");
    lines.push(`> ${item.text}`);
    lines.push("");
    if (item.confirmNote) {
      lines.push(`Founder review note: ${item.confirmNote}`);
      lines.push("");
    }
    lines.push("- [ ] True as written");
    lines.push("- [ ] True with edit");
    lines.push("- [ ] Not mine");
    lines.push("");
    n += 1;
  }

  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, lines.join("\n"));
  console.log(`Wrote ${items.length} confirm items to ${path.relative(rootDir, outputPath)}`);
}

main().catch((error) => {
  console.error("Failed to generate review checklist:", error);
  process.exit(1);
});
